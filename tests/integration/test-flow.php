<?php
define( 'IT_PORT', getenv( 'PORT' ) ?: '4010' );
define( 'IT_BASE', 'http://127.0.0.1:' . IT_PORT . '/api/woocommerce' );

function it_ctl( $path, $body = null ) {
	$ch = curl_init( 'http://127.0.0.1:' . IT_PORT . $path );
	curl_setopt_array( $ch, array( CURLOPT_RETURNTRANSFER => true, CURLOPT_POST => null !== $body, CURLOPT_POSTFIELDS => null === $body ? '' : json_encode( $body ) ) );
	$out = curl_exec( $ch );
	return json_decode( (string) $out, true );
}
function backend() {
	return it_ctl( '/__state' );
}
function it_reset() {
	it_ctl( '/__reset' );
}
/** Register through the real one-click connect handler; returns [store_id, api_key]. */
function it_connect( $email = 'owner@shop.example' ) {
	$s = run_scenario( 'connect', array( 'api_base' => IT_BASE, 'email' => $email ) );
	$set = $s['options']['cartrenew_wc_settings'] ?? array();
	return array( $set['store_id'] ?? null, $set['api_key'] ?? null, $s );
}
function it_configure( $store_id, $api_key ) {
	update_option( 'cartrenew_wc_settings', array( 'store_id' => $store_id, 'api_key' => $api_key, 'api_base' => IT_BASE, 'abandon_minutes' => 20, 'enabled' => 1 ) );
}
function it_store( $id ) {
	foreach ( backend()['db']['stores'] as $s ) {
		if ( $s['id'] === $id ) {
			return $s;
		}
	}
	return null;
}

test( 'IT connect: one-click creates a real store (billing pending) and plugin saves its credentials', function () {
	it_reset();
	list( $id, $key, $s ) = it_connect();
	assert_true( null !== $id && null !== $key, 'credentials saved' );
	$store = it_store( $id );
	assert_same( $key, $store['api_key'] );
	assert_same( 'pending', $store['billing_status'] );
	assert_same( 'woocommerce', $store['platform'] );
	assert_same( 'owner@shop.example', $store['contact_email'] );
	assert_same( 'https://shop.example', $store['site_url'] );
	assert_same( 'success', $s['transients']['cartrenew_wc_flash_1']['type'] );
} );

test( 'IT connect: second connect from same site -> 409, store_id kept, no key', function () {
	it_reset();
