	assert_count( 1, backend()['db']['stores'] );
} );

test( 'IT connect: backend rejects bad email, plugin shows error and saves nothing', function () {
	it_reset();
	// plugin validates first; bypass by checking the backend directly with what the plugin would send
	$r = it_http_post( IT_BASE . '/register-store', array( 'headers' => array( 'Content-Type' => 'application/json' ), 'body' => json_encode( array( 'email' => 'bad', 'site_url' => 'https://shop.example' ) ) ) );
	assert_same( 400, $r['response']['code'] );
