test( 'IT cap: free limit (3) -> 4th cart gets 402, plugin pauses and keeps it tracking', function () {
	it_reset();
	list( $id, $key ) = it_connect();
	it_configure( $id, $key );
	foreach ( array( 'c1', 'c2', 'c3', 'c4', 'c5' ) as $i => $k ) {
		seed_cart( $k, 100 - $i );
	}
	CartRenew_WC_Cron::run();
	assert_count( 3, backend()['sent'], 'three free messages' );
	assert_same( 'sent', row_by_key( 'c3' )->status );
	assert_same( 'tracking', row_by_key( 'c4' )->status, 'not marked failed' );
	assert_same( 'tracking', row_by_key( 'c5' )->status );
	assert_same( 1, get_transient( CartRenew_WC_Settings::LIMIT_FLAG ), 'plugin paused' );
	assert_count( 4, array_filter( $GLOBALS['wp']['http_calls'], function ( $c ) { return false !== strpos( $c['url'], 'abandoned-cart' ); } ), '3 sends + 1 rejected, then stopped' );
} );

test( 'IT cap: manual override (-1) lifts the cap; after flag clears sending resumes', function () {
	it_reset();
	list( $id, $key ) = it_connect();
	it_configure( $id, $key );
	foreach ( array( 'c1', 'c2', 'c3', 'c4' ) as $i => $k ) {
		seed_cart( $k, 100 - $i );
	}
	CartRenew_WC_Cron::run();
	assert_same( 'tracking', row_by_key( 'c4' )->status );

	it_ctl( '/__patch', array( 'table' => 'stores', 'id' => $id, 'patch' => array( 'message_cap_override' => -1 ) ) );
	delete_transient( CartRenew_WC_Settings::LIMIT_FLAG ); // flag expires on its own after 6h
	CartRenew_WC_Cron::run();
	assert_same( 'sent', row_by_key( 'c4' )->status );
	assert_count( 4, backend()['sent'] );
} );

