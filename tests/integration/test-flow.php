test( 'IT feedback: deactivation survey lands in backend with versions', function () {
	it_reset();
	list( $id, $key ) = it_connect();
	it_configure( $id, $key );
	$_POST = array( 'reason' => 'features', 'comment' => 'Need SMS too' );
	try {
		CartRenew_WC_Feedback::ajax_feedback();
	} catch ( WpJsonResponse $r ) {
		assert_true( $r->success );
	}
	$rows = backend()['db']['woocommerce_plugin_feedback'];
	assert_count( 1, $rows );
	assert_same( 'features', $rows[0]['reason'] );
	assert_same( 'Need SMS too', $rows[0]['comment'] );
	assert_same( CARTRENEW_WC_VERSION, $rows[0]['plugin_version'] );
	assert_same( '9.4.0', $rows[0]['wc_version'] );
	assert_true( $rows[0]['connected'] );
} );

test( 'IT feedback: every reason the plugin offers is accepted by the backend', function () {
	it_reset();
	$m = new ReflectionMethod( 'CartRenew_WC_Feedback', 'reasons' );
	$m->setAccessible( true );
	foreach ( array_keys( $m->invoke( null ) ) as $reason ) {
		$r = it_http_post( IT_BASE . '/feedback', array( 'headers' => array( 'Content-Type' => 'application/json' ), 'body' => json_encode( array( 'reason' => $reason ) ) ) );
		assert_same( 200, $r['response']['code'], $reason );
	}
} );
