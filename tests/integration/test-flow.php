test( 'IT send: abandoned cart reaches backend, WhatsApp "sent", plugin marks cart sent', function () {
	it_reset();
	list( $id, $key ) = it_connect();
	it_configure( $id, $key );
	seed_cart( 'session_abc', 60, array( 'restore_token' => 'TOKENTOKENTOKENTOKEN99' ) );
	CartRenew_WC_Cron::run();

	$row = row_by_key( 'session_abc' );
	assert_same( 'sent', $row->status );

	$b = backend();
	assert_count( 1, $b['sent'] );
	$m = $b['sent'][0];
	assert_same( $id, $m['storeId'] );
	assert_same( '+919876543210', $m['customerPhone'], 'backend normalises to E.164' );
	assert_same( 'Asha', $m['customerName'] );
	assert_same( 'https://shop.example/cart/?cartrenew_restore=TOKENTOKENTOKENTOKEN99', $m['checkoutUrl'] );
	assert_same( 'Tee', $m['items'][0]['name'] );
	assert_same( 2, $m['items'][0]['quantity'] );
	assert_same( 25, $m['cartValue'] );
	assert_same( 'messaged', $b['db']['abandoned_carts'][0]['status'] );
	assert_same( 'woocommerce:' . $id . ':session_abc', $b['db']['abandoned_carts'][0]['external_cart_key'] );
} );

test( 'IT send: restore link in WhatsApp message is accepted by the plugin restore handler', function () {
	it_reset();
	list( $id, $key ) = it_connect();
	it_configure( $id, $key );
	seed_cart( 'session_abc', 60 ); // token generated by seed helper
	CartRenew_WC_Cron::run();
	$url = backend()['sent'][0]['checkoutUrl'];
	parse_str( parse_url( $url, PHP_URL_QUERY ), $q );
	assert_same( 1, preg_match( '/^[A-Za-z0-9]{16,64}$/', $q['cartrenew_restore'] ), 'token format' );
	$tok = $q['cartrenew_restore'];
	$s   = run_scenario( 'restore', array( 'token' => $tok, 'seed' => array( 'minutes_ago' => 60, 'overrides' => array( 'restore_token' => $tok, 'status' => 'sent' ) ) ) );
	assert_same( array( 'https://shop.example/checkout/' ), $s['redirects'] );
	assert_count( 1, $s['cart_added'] );
} );

